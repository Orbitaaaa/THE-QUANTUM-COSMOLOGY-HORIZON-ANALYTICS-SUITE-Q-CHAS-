"""Round 6p: independent mathematical audit of Rounds 6l-6o.  Writes DATA/round6p_audit.json and AUDIT_ROUND6P.md."""
import json
import os
import warnings

from _common import DATA, ROOT, dump
from babyuniverse import audit6p as A

warnings.simplefilter("ignore")
rows = A.run_all_checks(heavy=True)
dump("round6p_audit.json", rows)
n_pass = sum(r["passed"] for r in rows)
lines = ["# Round 6p — independent mathematical audit (ledger)", "",
         f"{n_pass} of {len(rows)} checks passed. Each check re-derives a result by a different route (symbolic algebra, direct Riemann "
         "computation, or an independent numerical method). Generated by `CODE/scripts/round6p.py`.", "",
         "| # | check | result | detail | claim audited |", "|---|---|---|---|---|"]
for i, r in enumerate(rows, 1):
    lines.append(f"| {i} | {r['check']} | {'pass' if r['passed'] else 'FAIL'} | {r['detail']} | {r['source']} |")
open(os.path.join(ROOT, "AUDIT_ROUND6P.md"), "w").write("\n".join(lines) + "\n")
print(n_pass, "of", len(rows))
